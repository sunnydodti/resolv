"""
GitHubPlatformSubAgent — Hybrid agent for GitHub platform integration.
Handles PR creation, issue comments, PR summaries, and issue gaps reports.
"""
import os
import requests
from typing import Dict, Optional, Any

from agents.base import SubAgent
from core.logger import ResolvLogger


class GitHubPlatformSubAgent(SubAgent):
    """
    Interfaces with GitHub remote repository hosting.
    Operations: OpenPullRequest, FetchIssueComments, GeneratePRSummary, GenerateIssueGapsReport.
    """

    def __init__(self, logger: ResolvLogger, config):
        super().__init__(logger, config)
        self.token = None
        self.api_base = "https://api.github.com"

    def _authenticate(self, token: Optional[str] = None):
        """Authenticate with GitHub using token from credentials."""
        if token:
            self.token = token
        elif self.token is None:
            # Try to resolve from config
            from config.models import CredentialsStore
            # Token would be passed in from session credentials
            pass

    def _headers(self) -> dict:
        return {
            "Authorization": f"token {self.token}",
            "Accept": "application/vnd.github.v3+json",
            "User-Agent": "Resolv-Autonomous-Agent",
        }

    def open_pull_request(
        self,
        title: str,
        body: str,
        head: str,
        base: str = "main",
        draft: bool = False,
        repo_full_name: Optional[str] = None,
    ) -> str:
        """
        Open a Pull Request on GitHub.
        Returns the PR URL.
        FAIL EARLY: repo_full_name and token are required.
        """
        if not self.token:
            self.logger.error("GitHub token not configured. Cannot open PR.")
            raise ValueError("GitHub token required for PR creation")

        if not repo_full_name:
            self.logger.error("repo_full_name is required to open a Pull Request")
            raise ValueError("repo_full_name required for PR creation")

        url = f"{self.api_base}/repos/{repo_full_name}/pulls"
        payload = {
            "title": title,
            "body": body,
            "head": head,
            "base": base,
            "draft": draft,
        }

        self.logger.info(f"Opening PR: {head} -> {base} ({'draft' if draft else 'ready-for-review'})")

        try:
            response = requests.post(url, json=payload, headers=self._headers(), timeout=30)
            response.raise_for_status()
            data = response.json()
            pr_url = data.get("html_url", "")
            pr_number = data.get("number", "?")
            self.logger.success(f"Pull Request #{pr_number} opened: {pr_url}")
            return pr_url
        except requests.exceptions.RequestException as e:
            self.logger.error(f"Failed to open PR: {e}")
            if hasattr(e, 'response') and e.response is not None:
                self.logger.error(f"Response: {e.response.text}")
            raise

    def fetch_issue_comments(self, issue_number: int, repo_full_name: Optional[str] = None) -> list:
        """Fetch comments from a GitHub issue.
        FAIL EARLY: repo_full_name and token are required.
        """
        if not self.token:
            self.logger.error("GitHub token not configured.")
            raise ValueError("GitHub token required")

        if not repo_full_name:
            self.logger.error("repo_full_name is required to fetch issue comments")
            raise ValueError("repo_full_name required for fetching comments")

        url = f"{self.api_base}/repos/{repo_full_name}/issues/{issue_number}/comments"
        try:
            response = requests.get(url, headers=self._headers(), timeout=30)
            response.raise_for_status()
            return response.json()
        except requests.exceptions.RequestException as e:
            self.logger.error(f"Failed to fetch issue comments: {e}")
            return []

    def generate_pr_summary(self, diff: str, test_results: Optional[dict] = None) -> dict:
        """
        Generate AI-powered PR summary from diff and test results.
        This is a placeholder — the actual LLM call would be done by PlannerAgent/CodingAgent.
        """
        test_status = "passed"
        if test_results and test_results.get("returncode", 0) != 0:
            test_status = "failed"

        code_block = f"```diff\n{diff[:2000]}\n```"

        return {
            "title": f"fix: auto-resolved via Resolv",
            "body": f"""## Summary

This PR was automatically generated by Resolv, an autonomous issue-to-PR CLI agent.

## Changes

{code_block}

## Test Results

- Status: {test_status}
- Details: Automated test execution via Resolv sandbox

## Generated by Resolv

*This PR was created by an autonomous agent. Please review before merging.*
""",
        }

    def generate_issue_gaps_report(
        self,
        errors: list,
        attempted_fixes: list,
        repo_full_name: Optional[str] = None,
    ) -> str:
        """
        Generate an "Issue Gaps" report for budget exhaustion scenarios.
        Returns the report body text.
        """
        report = f"""# Issue Gaps Report

## Summary

Resolv exhausted its self-healing budget and could not fully resolve this issue.

## Errors Encountered

"""
        for i, err in enumerate(errors, 1):
            report += f"{i}. {err}\n"

        report += f"""
## Attempted Fixes

"""
        for i, fix in enumerate(attempted_fixes, 1):
            report += f"{i}. {fix}\n"

        report += f"""
## Recommendation

Manual intervention is required to complete this issue.

*Generated by Resolv Autonomous Agent*
"""
        return report
